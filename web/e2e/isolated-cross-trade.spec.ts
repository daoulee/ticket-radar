import { expect, test } from '@playwright/test'

// Only synthetic accounts and an isolated memory server; never run against the existing project server.
test('앱 API가 등록한 매물을 웹에서 구매하고 판매자 전달 후 수령한다', async ({ page, request }) => {
  test.skip(process.env.AID_CROSS_ISOLATED !== '1', 'requires dedicated isolated server and web preview')
  const root = 'http://127.0.0.1:31761'
  const response = await request.post(`${root}/auth/login`, { data: { name: 'appseller', password: 'Seller-pass-1!' } })
  expect(response.ok()).toBeTruthy()
  const sellerToken = (await response.json()).token as string
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('http://127.0.0.1:5174/')
  await page.getByRole('button', { name: '바로 체험하기' }).click()
  await page.getByLabel('아이디 또는 이메일').fill('webbuyer')
  await page.getByLabel('비밀번호').fill('Buyer-pass-1!')
  await page.getByRole('button', { name: '로그인', exact: true }).click()
  await page.getByRole('button', { name: /\[가상\] 뮤지컬/ }).click()
  const listing = page.locator('.market-item').filter({ hasText: 'VIP · 1매' }).filter({ hasText: '99,000원' }).last()
  await expect(listing).toBeVisible()
  await listing.getByRole('button', { name: '시연 구매하기' }).click()
  await expect(page.getByText('전달 대기')).toBeVisible()
  const sellerOrders = await request.get(`${root}/me/orders`, { headers: { Authorization: `Bearer ${sellerToken}` } })
  const order = (await sellerOrders.json()).find((item: { role: string; order: { status: string; amount: number } }) => item.role === 'seller' && item.order.status === 'held' && item.order.amount === 99000)
  expect(order).toBeTruthy()
  const sent = await request.post(`${root}/orders/${order.order.id}/sent`, { headers: { Authorization: `Bearer ${sellerToken}` } })
  expect(sent.ok()).toBeTruthy()
  await page.getByRole('button', { name: '내 거래' }).click()
  await page.getByRole('button', { name: '티켓 받았어요' }).click()
  await expect(page.getByText('거래 완료')).toBeVisible()
  const latest = await request.get(`${root}/orders/${order.order.id}`, { headers: { Authorization: `Bearer ${sellerToken}` } })
  expect((await latest.json()).order.status).toBe('settled')
})

test('웹에서 등록한 시연 매물을 앱 API 방식으로 구매하고 양쪽 상태를 확인한다', async ({ page, request }) => {
  test.skip(process.env.AID_CROSS_ISOLATED !== '1', 'requires dedicated isolated server and web preview')
  const root = 'http://127.0.0.1:31761'
  const response = await request.post(`${root}/auth/login`, { data: { name: 'appseller', password: 'Seller-pass-1!' } })
  expect(response.ok()).toBeTruthy()
  const buyerToken = (await response.json()).token as string
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('http://127.0.0.1:5174/')
  await page.getByRole('button', { name: '바로 체험하기' }).click()
  await page.getByLabel('아이디 또는 이메일').fill('webbuyer')
  await page.getByLabel('비밀번호').fill('Buyer-pass-1!')
  await page.getByRole('button', { name: '로그인', exact: true }).click()
  await page.getByRole('button', { name: /\[가상\] 뮤지컬/ }).click()
  await page.getByLabel('원구매가').fill('100000')
  await page.getByLabel('장당 가격').fill('95000')
  await page.getByRole('button', { name: '시연 매물 등록' }).click()
  await expect(page.getByText('시연 매물을 등록했어요.')).toBeVisible()
  const showResponse = await request.get(`${root}/shows/demo-musical`)
  const show = await showResponse.json()
  const listing = show.listings.find((item: { pricePerTicket: number; status: string }) => item.pricePerTicket === 95000 && item.status === 'active')
  expect(listing).toBeTruthy()
  const purchase = await request.post(`${root}/orders`, { headers: { Authorization: `Bearer ${buyerToken}` }, data: { listingId: listing.id } })
  expect(purchase.status()).toBe(201)
  const order = await purchase.json()
  await page.getByRole('button', { name: '내 거래' }).click()
  await page.locator('.market-extra').filter({ hasText: '95,000원' }).getByRole('button', { name: '전달했어요' }).click()
  await expect(page.getByText('티켓 전달을 표시했어요.')).toBeVisible()
  const confirm = await request.post(`${root}/orders/${order.id}/confirm`, { headers: { Authorization: `Bearer ${buyerToken}` } })
  expect(confirm.ok()).toBeTruthy()
  await page.getByRole('button', { name: '내 거래' }).click()
  await expect(page.getByText('거래 완료')).toBeVisible()
})
