import { expect, test } from '@playwright/test'

test('체험 화면 앞뒤 이동과 동작 줄이기', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('button', { name: '서비스 체험하러 가기' }).click()
  const market = page.getByRole('main', { name: '티켓 예매와 양도 시연' })
  await expect(market).toBeVisible()
  await expect(market).toHaveCSS('animation-name', 'none')
  await market.getByRole('button', { name: /뮤지컬 나침반/ }).first().click()
  const compassPoster = market.getByRole('img', { name: '뮤지컬 나침반 가상 공연 포스터' })
  await expect(compassPoster).toBeVisible()
  await expect.poll(() => compassPoster.evaluate((image: HTMLImageElement) => image.naturalWidth), { timeout: 20000 }).toBeGreaterThan(0)
  await expect(market.locator('.market-view')).toHaveClass(/market-view--forward/)
  await expect(market.locator('.market-view')).toHaveCSS('animation-name', 'none')
  await market.getByLabel('시연 구매 수량').selectOption('2')
  await market.getByRole('button', { name: /구매 정보 확인하기/ }).click()
  await market.getByRole('button', { name: '대기 건너뛰기' }).click()
  await market.getByRole('button', { name: 'A1 좌석' }).click()
  await market.getByRole('button', { name: 'A2 좌석' }).click()
  await market.getByRole('button', { name: /선택한 좌석 확인하기/ }).click()
  await market.getByRole('button', { name: '← 이전으로' }).click()
  await market.getByRole('button', { name: '← 이전으로' }).click()
  await expect(market.locator('.market-view')).toHaveClass(/market-view--back/)
  await expect(market.getByLabel('시연 구매 수량')).toHaveValue('2')
})

