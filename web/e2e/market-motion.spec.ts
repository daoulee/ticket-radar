test('모바일 가상 대기·좌석·시연 결제와 브라우저 내역', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('button', { name: '서비스 체험하러 가기' }).click()
  const market = page.getByRole('main', { name: '티켓 예매와 양도 시연' })
  await market.getByRole('button', { name: /뮤지컬 나침반/ }).first().click()
  await market.getByRole('button', { name: /구매 정보 확인하기/ }).click()
  await expect(market.getByText('가상 대기열 · 예매 시연')).toBeVisible()
  await market.getByRole('button', { name: '대기 건너뛰기' }).click()
  await expect(market.getByRole('button', { name: 'A3 좌석 · 선택 불가' })).toBeDisabled()
  await page.screenshot({ path: '/private/tmp/aid-demo-seats.png' })
  await market.getByRole('button', { name: 'A1 좌석' }).click()
  await market.getByRole('button', { name: /선택한 좌석 확인하기/ }).click()
  const reviewPoster = market.getByRole('img', { name: '뮤지컬 나침반 가상 공연 포스터' })
  await expect(reviewPoster).toBeVisible()
  await expect.poll(() => reviewPoster.evaluate((image: HTMLImageElement) => image.naturalWidth), { timeout: 20000 }).toBeGreaterThan(0)
  for (const width of [390, 1280]) {
    await page.setViewportSize({ width, height: 844 })
    await reviewPoster.scrollIntoViewIfNeeded()
    await page.screenshot({ path: `/private/tmp/aid-review-${width}.png` })
    expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(0)
  }
  await market.getByRole('button', { name: /시연 결제 계속하기/ }).click()
  const card = market.getByRole('radio', { name: '카드' })
  const bank = market.getByRole('radio', { name: '계좌이체' })
  await expect(card).toBeChecked()
  await bank.check()
  await expect(bank).toBeChecked()
  await expect(bank.locator('..')).toHaveClass('is-selected')
  await expect(card.locator('..')).not.toHaveClass('is-selected')
  for (const width of [390, 1280]) {
    await page.setViewportSize({ width, height: 844 })
    const layout = await bank.evaluate(input => {
      const box = input.getBoundingClientRect()
      const label = input.closest('label')!
      const range = document.createRange()
      range.selectNodeContents(label.lastChild!)
      return { inputWidth: box.width, textLines: range.getClientRects().length, labelHeight: label.getBoundingClientRect().height }
    })
    expect(layout.inputWidth).toBeLessThanOrEqual(22)
    expect(layout.textLines).toBe(1)
    expect(layout.labelHeight).toBeGreaterThanOrEqual(48)
    await expect(bank.locator('..')).toHaveCSS('background-color', 'rgb(241, 242, 250)')
    await expect(card.locator('..')).not.toHaveCSS('background-color', 'rgb(241, 242, 250)')
    await page.screenshot({ path: `/private/tmp/aid-payment-${width}.png` })
  }
  await market.getByRole('button', { name: '110,000원 시연 결제하기' }).click()
  await expect(market.getByRole('heading', { name: '시연 결제를 처리하고 있어요' })).toBeVisible()
  await expect(market.getByRole('heading', { name: '시연 결제가 완료됐어요' })).toBeVisible()
  await expect(market.getByText('계좌이체', { exact: true })).toBeVisible()
  await page.screenshot({ path: '/private/tmp/aid-demo-paid.png' })
  await market.getByRole('button', { name: '다른 티켓 둘러보기' }).click()
  await expect(market.getByText(/내 시연 예매 · 뮤지컬 나침반/)).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(0)
})

