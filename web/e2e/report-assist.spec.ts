import { expect, test } from '@playwright/test'

test('시연 결과의 신고 준비를 브라우저에서 복사하고 인쇄한다', async ({ page, context }) => {
  test.skip(test.info().project.use.browserName !== 'chromium', '클립보드 권한과 PDF 생성은 Chromium에서 검증한다')
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('button', { name: '서비스 체험하러 가기' }).click()
  await page.getByRole('button', { name: /판매글 안심 확인/ }).click()
  await page.getByRole('button', { name: /레이더 라이브/ }).first().click()
  await page.locator('details.samples summary').click()
  await page.getByRole('button', { name: '예시 1 · 가격 차이와 캡처 전달' }).click()
  await page.getByRole('button', { name: '판매글에서 정보 추출' }).click()
  await page.getByLabel('선택한 공연에 대한 판매글인가요?').selectOption('demo-radar-live')
  await page.getByLabel('가격 기준').selectOption('per_ticket')
  await page.getByLabel('수수료 포함 여부').selectOption('ticket_only')
  await page.getByLabel('할인 여부').selectOption('standard')
  await page.getByRole('button', { name: '이 값으로 공식 자료와 대조' }).click()
  await expect(page.getByText('시연 결과는 실제 신고에 사용하지 마세요.')).toBeVisible()
  await page.getByLabel('판매글 링크 (선택)').fill('https://example.org/demo')
  await page.getByRole('button', { name: '신고 준비 내용 복사' }).click()
  const text = await page.evaluate(() => navigator.clipboard.readText())
  expect(text).toContain('시연 데이터 · 실제 신고에 사용하지 마세요')
  expect(text).toContain('판매글 링크: https://example.org/demo')
  expect(text).toContain('공식 가격:')
  await page.pdf({ path: '/private/tmp/aid-report-print-check.pdf', format: 'A4', printBackground: true })
})
