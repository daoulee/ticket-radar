import { render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import { Marketplace } from './Marketplace'

describe('예매·원구매가 이하 양도 시연', () => {
  it('앞뒤 화면 이동은 즉시 가능하고 선택한 수량을 유지한다', async () => {
    const user = userEvent.setup()
    render(<Marketplace onSafety={vi.fn()} onPerformances={vi.fn()} />)
    await user.click(screen.getAllByRole('button', { name: /뮤지컬 나침반/ })[0])
    await user.selectOptions(screen.getByLabelText('시연 구매 수량'), '2')
    await user.click(screen.getByRole('button', { name: /구매 정보 확인하기/ }))
    await user.click(screen.getByRole('button', { name: '대기 건너뛰기' }))
    await user.click(screen.getByRole('button', { name: 'A1 좌석' }))
    await user.click(screen.getByRole('button', { name: 'A2 좌석' }))
    await user.click(screen.getByRole('button', { name: /선택한 좌석 확인하기/ }))
    expect(screen.getByText('R석 · A1, A2')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: '← 이전으로' }))
    await user.click(screen.getByRole('button', { name: '← 이전으로' }))
    expect(screen.getByLabelText('시연 구매 수량')).toHaveValue('2')
    expect(screen.getByRole('button', { name: '← 목록으로' }).closest('.market-view')).toHaveClass('market-view--back')
  })
  it('원 구매가 초과는 거부하고 더 낮은 양도가를 허용한다', async () => {
    const user = userEvent.setup()
    render(<Marketplace onSafety={vi.fn()} onPerformances={vi.fn()} />)
    await user.click(screen.getByRole('button', { name: /양도 등록하기/ }))
    await user.type(screen.getByLabelText('원 구매가 (1매)'), '100000')
    await user.type(screen.getByLabelText('양도가 (1매)'), '120000')
    await user.click(screen.getByRole('button', { name: '시연 매물 등록하기' }))
    expect(screen.getByRole('alert')).toHaveTextContent('원 구매가 이하여야')
    await user.clear(screen.getByLabelText('양도가 (1매)'))
    await user.type(screen.getByLabelText('양도가 (1매)'), '90000')
    await user.click(screen.getByRole('button', { name: '시연 매물 등록하기' }))
    expect(screen.getByText(/원구매가 이하 양도 시연 · 가상 데이터/)).toBeInTheDocument()
    expect(screen.getByText('90,000원 / 1매')).toBeInTheDocument()
    expect(screen.getByText('100,000원 / 1매')).toBeInTheDocument()
    expect(screen.getByRole('img', { name: '레이더 라이브 2026 가상 공연 포스터' })).toHaveAttribute('src', '/images/demo/radar-live-poster.webp')
    await user.click(screen.getByRole('button', { name: /구매 정보 확인하기/ }))
    expect(screen.getByRole('button', { name: /시연 결제 계속하기/ })).toBeEnabled()
    expect(screen.getByText(/결제, 좌석 예약과 티켓 양도는 진행되지 않습니다/)).toBeInTheDocument()
  })
  it('양도가가 좌석 시연 기준가를 넘으면 등록하지 않는다', async () => {
    const user = userEvent.setup()
    render(<Marketplace onSafety={vi.fn()} onPerformances={vi.fn()} />)
    await user.click(screen.getByRole('button', { name: /양도 등록하기/ }))
    expect(screen.getByText(/시연 기준가\(154,000원\) 이하/)).toBeInTheDocument()
    await user.type(screen.getByLabelText('원 구매가 (1매)'), '900000')
    await user.type(screen.getByLabelText('양도가 (1매)'), '900000')
    await user.click(screen.getByRole('button', { name: '시연 매물 등록하기' }))
    expect(screen.getByRole('alert')).toHaveTextContent('시연 기준가 154,000원 이하')
    await user.clear(screen.getByLabelText('원 구매가 (1매)')); await user.type(screen.getByLabelText('원 구매가 (1매)'), '154000')
    await user.clear(screen.getByLabelText('양도가 (1매)')); await user.type(screen.getByLabelText('양도가 (1매)'), '154000')
    await user.click(screen.getByRole('button', { name: '시연 매물 등록하기' }))
    expect(screen.getAllByText('154,000원 / 1매')).toHaveLength(2)
  })
  it('공식 예매와 양도 시연을 구분해 검색한다', async () => {
    const user = userEvent.setup()
    render(<Marketplace onSafety={vi.fn()} onPerformances={vi.fn()} />)
    await user.click(screen.getByRole('button', { name: '공식 예매 시연', pressed: false }))
    expect(screen.getAllByText('공식 예매 시연')).toHaveLength(3)
    expect(screen.queryByText('원구매가 이하 양도 시연', { selector: '.market-pill' })).not.toBeInTheDocument()
    await user.type(screen.getByRole('searchbox', { name: '시연 공연 검색' }), '나침반')
    expect(screen.getByText('뮤지컬 나침반')).toBeInTheDocument()
    expect(screen.queryByText('레이더 라이브 2026')).not.toBeInTheDocument()
  })
  it('공연을 바꾸면 해당 공연의 회차와 좌석만 선택한다', async () => {
    const user = userEvent.setup()
    render(<Marketplace onSafety={vi.fn()} onPerformances={vi.fn()} />)
    await user.click(screen.getByRole('button', { name: /양도 등록하기/ }))
    expect(screen.getByLabelText('가상 좌석')).toHaveValue('VIP')
    await user.selectOptions(screen.getByLabelText('가상 공연'), 'demo-market-compass')
    expect(screen.getByLabelText('가상 회차')).toHaveValue('demo-market-compass-s1')
    expect(screen.getByLabelText('가상 좌석')).toHaveValue('R')
    expect(screen.queryByRole('option', { name: 'VIP석' })).not.toBeInTheDocument()
    await user.selectOptions(screen.getByLabelText('가상 공연'), 'demo-market-live')
    expect(screen.getByLabelText('가상 회차')).toHaveValue('demo-market-live-s1')
    expect(screen.getByLabelText('가상 좌석')).toHaveValue('VIP')
    expect(screen.queryByRole('option', { name: 'S석' })).not.toBeInTheDocument()
  })
  it('가상 매물 수량 안에서만 선택하고 수수료를 제외한 시연 합계를 보여준다', async () => {
    const user = userEvent.setup()
    render(<Marketplace onSafety={vi.fn()} onPerformances={vi.fn()} />)
    await user.click(screen.getByRole('button', { name: '원구매가 이하 양도 시연', pressed: false }))
    await user.click(screen.getByText('뮤지컬 나침반').closest('button')!)
    expect(screen.getByLabelText('시연 구매 수량')).toHaveValue('1')
    expect(screen.queryByRole('option', { name: '2매' })).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: /구매 정보 확인하기/ }))
    expect(screen.getByText('S석 · 1매')).toBeInTheDocument()
    expect(screen.getByText('88,000원')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: /시연 결제 계속하기/ })).toBeEnabled()
    expect(screen.queryByText('가상 대기열 · 예매 시연')).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: /시연 결제 계속하기/ }))
    await user.click(screen.getByRole('button', { name: '88,000원 시연 결제하기' }))
    expect(await screen.findByRole('heading', { name: '시연 결제가 완료됐어요' }, { timeout: 3000 })).toBeInTheDocument()
  })
})
